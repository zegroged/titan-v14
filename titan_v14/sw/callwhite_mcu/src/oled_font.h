/**
 * @brief Draw a character at (x, page) position.
 * @param fb   Framebuffer pointer (1024 bytes)
 * @param x    X coordinate (0-127)
 * @param page Page number (0-7, each page = 8 pixels high)
 * @param c    ASCII character to draw
 */
static inline void oled_font_draw_char(uint8_t *fb, uint8_t x, uint8_t page,
                                       char c) {
  if (c < FONT_FIRST || c > FONT_LAST)
    c = '?';
  uint8_t idx = c - FONT_FIRST;
  uint16_t base = page * SSD1306_WIDTH + x;

  for (uint8_t col = 0; col < FONT_WIDTH; col++) {
    if (x + col < SSD1306_WIDTH)
      fb[base + col] = font_5x7[idx][col];
  }
  /* 1px spacing */
  if (x + FONT_WIDTH < SSD1306_WIDTH)
    fb[base + FONT_WIDTH] = 0x00;
}

/**
 * @brief Draw a null-terminated string at (x, page).
 * @return Number of characters drawn
 */
static inline int oled_font_draw_string(uint8_t *fb, uint8_t x, uint8_t page,
                                        const char *str) {
  int count = 0;
  while (*str && x + FONT_CHAR_W <= SSD1306_WIDTH) {
    oled_font_draw_char(fb, x, page, *str);
    x += FONT_CHAR_W;
    str++;
    count++;
  }
  return count;
}

